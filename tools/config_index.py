#!/usr/bin/env python3
"""Write docs/configs.md: one row per file in pack/config with what it is and its first comment line.

Usage: config_index.py           write the index
       config_index.py --check   exit 1 if docs/configs.md is out of date (used by validate.py)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "pack" / "config"
TARGET = ROOT / "docs" / "configs.md"
# Files the pack deliberately changed from the mod defaults; everything else is the default as generated.
CURATED = {
    "tensura/reincarnation_config.toml": "Human-only first spawn; Legendaries removed from the reincarnation skill pools",
    "greatsage-common.toml": "Legendaries excluded from Great Sage's reincarnation wishes; no reincarnation error chance",
    "tombstone-common.toml": "No graves in the Mortal dimensions and the Spirit Corridor",
    "DistantHorizons.toml": "Chat warnings and the auto-updater off",
    "enhancedcelestials2core/translations.json": "Translation prompt off",
    "lightmanscurrency/MasterCoinList.json": "Money = Tensura's four coins (10:1 steps), own ATM exchange buttons; Lightman's own coins are not money",
    "lightmanscurrency-common.txt": "No Lightman's coin loot, minting, banker/cashier villagers or village houses",
    "lightmanscurrency-server.txt": "Bank accounts and network traders refused in the Mortal dimensions; 5% auction fee",
    "easy_npc/security.cfg": "Dialog buttons may run `/ttl ...` as the player (executeAsUserCommandAllowList.ALL=ttl), for the guild NPCs",
    "easy_npc/preset/ttl_guild_fuze.npc.snbt": "Generated by tools/gen_npcs.py: Fuze, guildmaster of the Free Guild (high-rank contracts)",
    "easy_npc/preset/ttl_guild_receptionist.npc.snbt": "Generated by tools/gen_npcs.py: Free Guild receptionist (desk board, hand-ins, rank)",
    "easy_npc/preset/ttl_cast_<kind>.npc.snbt": "Generated by tools/gen_npcs.py: one preset per story cast kind (Talk button -> `/ttl story talk <id>`)",
    "simple-discord-link/simple-discord-link.toml": "Discord bot: token and channel from `${CFG_...}` env placeholders, tellraw relay off, test bots filtered",
}


def first_comment(path: Path) -> str:
    try:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines()[:40]:
            s = line.strip()
            if s.startswith(("#", "//")) and len(s.lstrip("#/ ").strip()) > 3:
                return s.lstrip("#/ ").strip().replace("|", "\|")[:110]
    except OSError:
        pass
    return ""


def kind(rel: str) -> str:
    name = rel.lower()
    if "server" in name or name.endswith(".snbt"):
        return "server"
    if "common" in name:
        return "common"
    return "-"


def render() -> str:
    files = sorted(p for p in CONFIG.rglob("*") if p.is_file())
    groups: dict[str, list[Path]] = {}
    for p in files:
        rel = p.relative_to(CONFIG).as_posix()
        top = rel.split("/")[0] if "/" in rel else rel.split("-")[0].split(".")[0].split("_")[0]
        groups.setdefault(top, []).append(p)
    out = [
        "# Configs",
        "",
        "GENERATED by `tools/config_index.py` — do not edit by hand. Every mod config the server uses lives in",
        "`pack/config/` (client-only configs excluded), ships with the pack, and is rewritten on the server from",
        "git on each start. To change one: edit the file, `python tools/validate.py`, open a PR.",
        "Gameplay numbers of our own systems are in `design/data/*.toml`, not here.",
        "",
        f"{len(files)} files. **Changed from the mod defaults:**",
        "",
    ]
    for rel, why in CURATED.items():
        out.append(f"- `{rel}` — {why}")
    out.append("")
    for top in sorted(groups):
        out += [f"## {top}", "", "| File | Side | First comment |", "|---|---|---|"]
        for p in groups[top]:
            rel = p.relative_to(CONFIG).as_posix()
            out.append(f"| `{rel}` | {kind(rel)} | {first_comment(p)} |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("FAIL docs/configs.md is stale: run python tools/config_index.py")
            sys.exit(1)
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
