#!/usr/bin/env python3
"""Generate the FTB Quests book (pack/config/ftbquests/quests/) from design/quests/*.toml.

Quests are written in friendly TOML (format: design/quests.md) and turned into FTB Quests 2101 SNBT:
data.snbt, chapters/<key>.snbt and lang/en_us.snbt (all text lives in the lang file since FTB Quests 2100),
plus pack/kubejs/server_scripts/ttl/generated/quests.js (quest ids for `/ttl quests check`).
Ids are stable: 16 hex digits of sha256("ttl/<chapter>/<quest>[/task|reward/<n or key>]"), so regenerating never
resets progress unless a key changes. Stdlib only.

Usage: gen_quests.py            write the files (and delete chapter files no longer in the TOML)
       gen_quests.py --check    exit 1 if any generated file is out of date (used by validate.py)
"""
import hashlib
import json
import math
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "design" / "quests"
TARGET = ROOT / "pack" / "config" / "ftbquests" / "quests"
IDS_JS = ROOT / "pack" / "kubejs" / "server_scripts" / "ttl" / "generated" / "quests.js"
HEADER = "# GENERATED by tools/gen_quests.py from design/quests/*.toml. Do not edit; edit the TOML and regenerate.\n"
FILE_VERSION = 13  # BaseQuestFile.VERSION in ftb-quests-neoforge-2101.1.39
SPACING = 1.5      # grid units between quests

TASK_TYPES = {"item", "kill", "dimension", "structure", "biome", "advancement", "stat", "stage", "checkmark",
              "location", "xp", "ep", "ability"}
REWARD_TYPES = {"item", "xp", "xp_levels"}  # never skill/race/awakening rewards (manas-integration.md §5(d))
QUEST_KEYS = {"key", "title", "subtitle", "icon", "deps", "lane", "col", "text", "karma", "tasks", "rewards",
              "optional", "shape", "size", "hide_until_deps_complete"}
SHAPES = {"circle", "square", "rsquare", "diamond", "pentagon", "hexagon", "octagon", "heart", "gear"}


class QuestError(Exception):
    pass


def qid(*parts: str) -> str:
    # FTB Quests parses ids as a signed long: an id with the top bit set (first hex digit 8-F) is rejected and the
    # object silently dropped, so the top bit is cleared. 0 and 1 are reserved (null object, the quest file itself).
    v = int(hashlib.sha256("/".join(("ttl",) + parts).encode()).hexdigest()[:16], 16) & 0x7FFFFFFFFFFFFFFF
    return "%016X" % (v if v > 1 else 0x7FFFFFFFFFFFFFFF)


# ---- SNBT writer (FTB Library style: tabs, one key per line, sorted keys) ---------------------------------

class IntArray(list):
    pass


def snbt_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def snbt(v, indent: int = 0) -> str:
    tab = "\t"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return f"{v!r}d"
    if isinstance(v, str):
        return snbt_str(v)
    if isinstance(v, IntArray):
        return "[I; " + ", ".join(str(int(x)) for x in v) + "]"
    if isinstance(v, list):
        if not v:
            return "[ ]"
        inner = "\n".join(tab * (indent + 1) + snbt(x, indent + 1) for x in v)
        return "[\n" + inner + "\n" + tab * indent + "]"
    if isinstance(v, dict):
        if not v:
            return "{ }"
        lines = []
        for k in sorted(v):
            key = k if all(c.isalnum() or c in "_.-" for c in k) else snbt_str(k)
            lines.append(f"{tab * (indent + 1)}{key}: {snbt(v[k], indent + 1)}")
        return "{\n" + "\n".join(lines) + "\n" + tab * indent + "}"
    raise TypeError(f"no SNBT for {type(v)}")


# ---- TOML → quest objects ------------------------------------------------------------------------------

def stack(item: str, count: int = 1) -> dict:
    if ":" not in item:
        raise QuestError(f"item id needs a namespace: {item}")
    return {"id": item, "count": int(count)}


def check_life_item(chapter: dict, where: str, item: str) -> None:
    if chapter.get("life") == 1 and not item.startswith("minecraft:"):
        raise QuestError(f"{where}: Life 1 has no modded content, {item} is not allowed (minecraft: only)")


def build_task(chapter: dict, where: str, t: dict, tid: str) -> tuple[dict, str | None]:
    kind = t.get("type")
    if kind not in TASK_TYPES:
        raise QuestError(f"{where}: unknown task type {kind!r} (one of {sorted(TASK_TYPES)})")
    if chapter.get("life") == 1 and kind in ("ep", "ability"):
        raise QuestError(f"{where}: Tensura task {kind!r} in a Life 1 chapter")
    out: dict = {"id": tid}
    if kind == "item":
        check_life_item(chapter, where, t["item"])
        out.update(type="item", item=stack(t["item"]), count=int(t.get("count", 1)), consume_items=False)
    elif kind == "kill":
        check_life_item(chapter, where, t["entity"])
        out.update(type="kill", entity=t["entity"], value=int(t.get("count", 1)))
    elif kind == "dimension":
        out.update(type="dimension", dimension=t["dimension"])
    elif kind == "structure":
        out.update(type="structure", structure=t["structure"])
    elif kind == "biome":
        out.update(type="biome", biome=t["biome"])
    elif kind == "advancement":
        out.update(type="advancement", advancement=t["advancement"], criterion=t.get("criterion", ""))
    elif kind == "stat":
        out.update(type="stat", stat=t["stat"], value=int(t["value"]))
    elif kind == "stage":
        out.update(type="gamestage", stage=t["stage"], team_stage=False)
    elif kind == "checkmark":
        out.update(type="checkmark")
    elif kind == "xp":
        out.update(type="xp", value=int(t["value"]), points=bool(t.get("points", False)))
    elif kind == "location":
        x, z = t["at"]
        r = int(t.get("radius", 32))
        out.update(type="location", dimension=t["dimension"], ignore_dimension=False,
                   position=IntArray([x - r, -64, z - r]), size=IntArray([2 * r + 1, 384, 2 * r + 1]))
    elif kind == "ep":
        out.update(type="tensura_ftb:existence_value", existence=t.get("existence", "EP"), value=int(t["value"]))
    elif kind == "ability":
        if t.get("status", "LEARNT") not in ("AVAILABLE", "LEARNT", "MASTERED"):
            raise QuestError(f"{where}: ability status must be AVAILABLE, LEARNT or MASTERED")
        out.update(type="tensura_ftb:ability", ability=t["ability"], status=t.get("status", "LEARNT"))
    return out, t.get("title")


def build_reward(chapter: dict, where: str, r: dict, rid: str) -> dict:
    kind = r.get("type")
    if kind not in REWARD_TYPES:
        raise QuestError(f"{where}: reward type {kind!r} is not allowed (one of {sorted(REWARD_TYPES)}); "
                         "quests never grant skills, races or evolutions")
    if kind == "item":
        check_life_item(chapter, where, r["item"])
        return {"id": rid, "type": "item", "item": stack(r["item"]), "count": int(r.get("count", 1))}
    if kind == "xp":
        return {"id": rid, "type": "xp", "xp": int(r["xp"])}
    return {"id": rid, "type": "xp_levels", "xp_levels": int(r["xp_levels"])}


def text_lines(s: str) -> list[str]:
    """TOML text → FTB description lines: lines within a paragraph are joined (FTB wraps them itself),
    a blank line starts a new paragraph."""
    paragraphs = [" ".join(line.strip() for line in p.split("\n") if line.strip())
                  for p in s.strip("\n").split("\n\n")]
    out: list[str] = []
    for p in paragraphs:
        if out:
            out.append("")
        out.append(p)
    return out if any(out) else []


def build_chapter(src: Path, data: dict, lang: dict) -> tuple[str, dict, dict]:
    ch = data.get("chapter") or {}
    ckey = ch.get("key")
    if not ckey or not ckey.replace("_", "").isalnum() or ckey != ckey.lower():
        raise QuestError(f"{src.name}: [chapter] needs a lowercase key (letters, digits, _)")
    cid = qid(ckey)
    quests = data.get("quests") or []
    keys = [q.get("key") for q in quests]
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes or None in keys:
        raise QuestError(f"{src.name}: every quest needs a unique key (duplicates: {sorted(dupes)})")
    by_key = {q["key"]: q for q in quests}

    cols: dict[str, int] = {}

    def col(k: str, seen: tuple = ()) -> int:
        if k in seen:
            raise QuestError(f"{src.name}: dependency loop through {k}")
        if k not in cols:
            q = by_key[k]
            deps = q.get("deps", [])
            cols[k] = q["col"] if "col" in q else (max((col(d, seen + (k,)) for d in deps), default=-1) + 1)
        return cols[k]

    spots: dict[tuple, str] = {}
    out_quests = []
    for q in quests:
        k = q["key"]
        where = f"{src.name}:{k}"
        unknown = set(q) - QUEST_KEYS
        if unknown:
            raise QuestError(f"{where}: unknown field(s) {sorted(unknown)}")
        for d in q.get("deps", []):
            if d not in by_key:
                raise QuestError(f"{where}: unknown dependency {d!r}")
        if not q.get("tasks"):
            raise QuestError(f"{where}: a quest needs at least one task")
        if not q.get("title"):
            raise QuestError(f"{where}: title missing")
        spot = (col(k), int(q.get("lane", 0)))
        if spot in spots:
            raise QuestError(f"{where}: same spot as {spots[spot]} (column {spot[0]}, lane {spot[1]}); set `col` or `lane`")
        spots[spot] = k
        qq = qid(ckey, k)
        tasks = []
        for i, t in enumerate(q["tasks"]):
            tid = qid(ckey, k, "task", str(t.get("key", i)))
            task, title = build_task(ch, where, t, tid)
            tasks.append(task)
            if title:
                lang[f"task.{tid}.title"] = title
        rewards = [build_reward(ch, where, r, qid(ckey, k, "reward", str(r.get("key", i))))
                   for i, r in enumerate(q.get("rewards", []))]
        quest = {
            "id": qq,
            "x": float(spot[0] * SPACING),
            "y": float(spot[1] * SPACING),
            "dependencies": [qid(ckey, d) for d in q.get("deps", [])],
            "tasks": tasks,
            "rewards": rewards,
        }
        if q.get("icon"):
            check_life_item(ch, where, q["icon"])
            quest["icon"] = stack(q["icon"])
        if q.get("shape"):
            if q["shape"] not in SHAPES:
                raise QuestError(f"{where}: shape must be one of {sorted(SHAPES)}")
            quest["shape"] = q["shape"]
        if q.get("size"):
            quest["size"] = float(q["size"])
        if q.get("optional"):
            quest["optional"] = True
        if q.get("hide_until_deps_complete", ch.get("hide_until_deps_complete", False)) and q.get("deps"):
            quest["hide_until_deps_complete"] = True
        out_quests.append(quest)

        lang[f"quest.{qq}.title"] = q["title"]
        if q.get("subtitle"):
            lang[f"quest.{qq}.quest_subtitle"] = q["subtitle"]
        desc = text_lines(q.get("text", ""))
        if q.get("karma"):
            label = "Next life" if ch.get("life") == 1 else "Why it matters"
            desc += ["", f"&6{label}:&r {q['karma'].strip()}"]
        if desc and any(desc):
            lang[f"quest.{qq}.quest_desc"] = desc

    icon = ch.get("icon", "minecraft:book")
    chapter = {
        "id": cid,
        "filename": ckey,
        "group": "",
        "order_index": int(ch.get("order", 0)),
        "icon": stack(icon),
        "default_quest_shape": "",
        "default_hide_dependency_lines": False,
        "quest_links": [],
        "images": [],
        "quests": out_quests,
    }
    lang[f"chapter.{cid}.title"] = ch.get("title", ckey)
    if ch.get("subtitle") or ch.get("text"):
        lang[f"chapter.{cid}.chapter_subtitle"] = [s for s in [ch.get("subtitle", "")] if s] + (
            text_lines(ch["text"]) if ch.get("text") else [])
    ids = {"id": cid, "quests": {q["key"]: qid(ckey, q["key"]) for q in quests}}
    return ckey, chapter, ids


def render() -> dict[Path, str]:
    lang: dict = {"file.0000000000000001.title": "OCS Tensura: Two Lives"}
    files: dict[Path, str] = {}
    ids: dict = {}
    seen_order = {}
    for src in sorted(SOURCES.glob("*.toml")):
        with src.open("rb") as f:
            data = tomllib.load(f)
        ckey, chapter, cids = build_chapter(src, data, lang)
        if ckey in ids:
            raise QuestError(f"{src.name}: chapter key {ckey} used twice")
        if chapter["order_index"] in seen_order:
            raise QuestError(f"{src.name}: order {chapter['order_index']} also used by {seen_order[chapter['order_index']]}")
        seen_order[chapter["order_index"]] = ckey
        ids[ckey] = cids
        files[TARGET / "chapters" / f"{ckey}.snbt"] = HEADER + snbt(chapter) + "\n"
    data_snbt = {
        "version": FILE_VERSION,
        "default_reward_team": False,
        "default_consume_items": False,
        "default_autoclaim_rewards": "disabled",
        "default_quest_shape": "circle",
        "default_quest_disable_jei": False,
        "emergency_items_cooldown": 300,
        "drop_loot_crates": False,
        "disable_gui": False,
        "grid_scale": 0.5,
        "pause_game": False,
        "lock_message": "",
        "progression_mode": "flexible",
        "show_lock_icons": True,
        "drop_book_on_death": False,
    }
    files[TARGET / "data.snbt"] = HEADER + snbt(data_snbt) + "\n"
    files[TARGET / "lang" / "en_us.snbt"] = HEADER + snbt(lang) + "\n"
    body = json.dumps(ids, indent=2, sort_keys=True)
    files[IDS_JS] = (
        "// priority: 200\n"
        "// GENERATED by tools/gen_quests.py from design/quests/*.toml. Do not edit; edit the TOML and regenerate.\n"
        "// FTB Quests ids per chapter and quest key, for /ttl quests check (quests/check.js).\n"
        f"const TtlQuestIds = {body}\n"
    )
    return files


def stale_chapters(files: dict[Path, str]) -> list[Path]:
    folder = TARGET / "chapters"
    return [p for p in folder.glob("*.snbt") if p not in files] if folder.exists() else []


def main() -> None:
    try:
        files = render()
    except (QuestError, KeyError, ValueError, TypeError) as e:
        print(f"FAIL gen_quests: {e}")
        sys.exit(1)
    if "--check" in sys.argv:
        bad = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        bad += stale_chapters(files)
        if bad:
            names = ", ".join(str(p.relative_to(ROOT)) for p in bad)
            print(f"FAIL quest book is stale ({names}): run python tools/gen_quests.py")
            sys.exit(1)
        return
    for p in stale_chapters(files):
        p.unlink()
        print(f"removed {p.relative_to(ROOT)}")
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {p.relative_to(ROOT)}")
    n = sum(len(c["quests"]) for c in json.loads(files[IDS_JS].split("const TtlQuestIds = ", 1)[1]).values())
    print(f"{len(files) - 3} chapters, {n} quests")


if __name__ == "__main__":
    main()
