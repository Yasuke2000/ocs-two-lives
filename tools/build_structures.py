#!/usr/bin/env python3
"""Turn every blueprints/<name>.py (code), .schem (WorldEdit) or .nbt (captured) into a structure + previews.

Writes pack/kubejs/data/ttl/structure/<name>.nbt (place in game: `/ttl build <name>`),
docs/previews/<name>-iso.png + <name>-top.png for review, and the gallery docs/previews/README.md.
Usage: build_structures.py [name ...]   (no names: all blueprints)
       build_structures.py --check      exit 1 if a structure file is out of date (validate.py)
"""
import ast
import hashlib
import importlib.util
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from blueprint import Blueprint, from_schem, from_structure  # noqa: E402
import nbt  # noqa: E402

BLUEPRINTS = ROOT / "blueprints"
sys.path.insert(0, str(BLUEPRINTS))  # shared helpers: blueprints/_*.py
STRUCTURES = ROOT / "pack" / "kubejs" / "data" / "ttl" / "structure"
PREVIEWS = ROOT / "docs" / "previews"


def load(path: Path) -> Blueprint:
    if path.suffix == ".schem":
        return from_schem(path.stem, path)
    if path.suffix == ".nbt":
        return from_structure(path.stem, path)
    spec = importlib.util.spec_from_file_location(f"blueprint_{path.stem}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    bp = Blueprint(path.stem, module.SIZE)
    module.build(bp)
    # Optional: PARTS = z offsets to split a big build into <name>_<i>.nbt slabs (placed one by one, less
    # lag, smaller files); outputs(bp) -> {repo-relative path: text} for generated data such as footprints.
    bp.parts = getattr(module, "PARTS", None)
    bp.outputs = module.outputs(bp) if hasattr(module, "outputs") else {}
    return bp


def structures(bp: Blueprint) -> dict:
    """Structure name -> NBT dict: the whole build, or one slab per PARTS z offset."""
    if not getattr(bp, "parts", None):
        return {bp.name: bp.to_structure()}
    sx, sy, sz = bp.size
    out = {}
    bounds = list(bp.parts) + [sz]
    for i, (z0, z1) in enumerate(zip(bounds, bounds[1:])):
        part = Blueprint(f"{bp.name}_{i}", (sx, sy, z1 - z0))
        part.blocks = {(x, y, z - z0): s for (x, y, z), s in bp.blocks.items() if z0 <= z < z1}
        out[part.name] = part.to_structure()
    return out


def summary(path: Path) -> str:
    """The blueprint's docstring as one line (or where it came from, for captured and WorldEdit builds)."""
    if path.suffix == ".schem":
        return "Polished in WorldEdit (`blueprints/%s`)." % path.name
    if path.suffix == ".nbt":
        return "Captured from the world (`blueprints/%s`)." % path.name
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    return " ".join(doc.split())


def gallery(files: list[Path]) -> str:
    lines = ["# Build gallery", "",
             "Generated by `python tools/build_structures.py` from `blueprints/`; do not edit by hand.",
             "Place any of these in game with `/ttl build <name>` (corner at your feet).", ""]
    for path in files:
        lines += [f"## {path.stem}", "", summary(path), "",
                  f"![{path.stem}]({path.stem}-iso.png) ![{path.stem} from above]({path.stem}-top.png)", ""]
    return "\n".join(lines)


def check_cache_key() -> str:
    """Hash of everything a blueprint build reads: blueprints/** (helpers and assets included) and the tools."""
    h = hashlib.sha256()
    tools = [ROOT / "tools" / n for n in ("blueprint.py", "nbt.py", "build_structures.py")]
    for path in sorted(p for p in BLUEPRINTS.rglob("*") if p.is_file() and "__pycache__" not in p.parts) + tools:
        h.update(path.relative_to(ROOT).as_posix().encode("utf-8") + b"\0" + path.read_bytes())
    return h.hexdigest()


def file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else ""


def main() -> None:
    check = "--check" in sys.argv
    names = [a for a in sys.argv[1:] if not a.startswith("--")]
    stale = []
    # Opt-in (tools/check.sh): a full --check rebuilds every blueprint (minutes). With TTL_STRUCTURE_CHECK_CACHE set,
    # a passing check is remembered under the hash of its inputs together with the hashes of the files it compared;
    # the next check passes at once only while both are unchanged. validate.py and CI on their own never cache.
    cache_dir = os.environ.get("TTL_STRUCTURE_CHECK_CACHE") if check and not names else None
    compared: list[Path] = []
    if cache_dir:
        marker = Path(cache_dir) / f"structures-{check_cache_key()}.json"
        try:
            seen = json.loads(marker.read_text(encoding="utf-8"))
            if seen and all(file_hash(ROOT / rel) == sha for rel, sha in seen.items()):
                print("structures: blueprints and structure files unchanged since a passing --check (cached)")
                return
        except (OSError, ValueError):
            pass
    # Captured from the world (.nbt, tools/capture.py) wins over polished in WorldEdit (.schem,
    # tools/import_schem.py), which wins over code (.py) of the same name.
    by_name = {p.stem: p for p in sorted(BLUEPRINTS.glob("*.py")) if not p.stem.startswith("_")}
    by_name.update({p.stem: p for p in sorted(BLUEPRINTS.glob("*.schem"))})
    by_name.update({p.stem: p for p in sorted(BLUEPRINTS.glob("*.nbt"))})
    files = [by_name[n] for n in sorted(by_name)]
    index = PREVIEWS / "README.md"
    if check:
        if not index.exists() or index.read_text(encoding="utf-8") != gallery(files):
            stale.append("docs/previews/README.md")
        compared.append(index)
    else:
        PREVIEWS.mkdir(parents=True, exist_ok=True)
        index.write_text(gallery(files), encoding="utf-8", newline="\n")
    if names:
        files = [f for f in files if f.stem in names]
    for path in files:
        bp = load(path)
        if check:
            for name, data in structures(bp).items():
                target = STRUCTURES / f"{name}.nbt"
                with tempfile.TemporaryDirectory() as tmp:
                    fresh = Path(tmp) / "x.nbt"
                    nbt.write_gzip(fresh, data)
                    if not target.exists() or target.read_bytes() != fresh.read_bytes():
                        stale.append(name)
                compared.append(target)
            for rel, text in getattr(bp, "outputs", {}).items():
                out = ROOT / rel
                if not out.exists() or out.read_text(encoding="utf-8") != text:
                    stale.append(rel)
                compared.append(out)
            continue
        STRUCTURES.mkdir(parents=True, exist_ok=True)
        for name, data in structures(bp).items():
            target = STRUCTURES / f"{name}.nbt"
            nbt.write_gzip(target, data)
            print(f"{name}: {len(data['blocks'])} blocks, size {tuple(data['size'])}, "
                  f"{target.stat().st_size // 1024} KB -> {target.relative_to(ROOT)}")
        for rel, text in getattr(bp, "outputs", {}).items():
            out = ROOT / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8", newline="\n")
            print(f"{bp.name}: wrote {rel} ({len(text) // 1024} KB)")
        bp.render(PREVIEWS / f"{bp.name}-iso.png", PREVIEWS / f"{bp.name}-top.png")
    if stale:
        print("FAIL structures out of date: " + ", ".join(stale) + " (run python tools/build_structures.py)")
        sys.exit(1)
    if cache_dir:
        try:
            marker.parent.mkdir(parents=True, exist_ok=True)
            tmp = marker.with_suffix(f".{os.getpid()}.tmp")
            tmp.write_text(json.dumps({p.relative_to(ROOT).as_posix(): file_hash(p) for p in compared}), encoding="utf-8")
            os.replace(tmp, marker)
        except OSError:
            pass


if __name__ == "__main__":
    main()
