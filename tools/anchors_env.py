"""tests/anchors.env: the numbers the in-game bot tests read (design/architecture/lerfing-import.md §3.5, WP-L6).

tools/gen_data.py calls render() on every run (and `--check`, which validate.py runs), so the file never goes stale:

    anchor.<id>.x / .z      every [<id>] table of design/data/anchors.toml (Tempest, the arrival, Dwargon, every build ...)
    probe.<id>.<field>      every [<id>] table of design/data/lerfing/probes.toml (x, y, z, block, biome, weight, kind)

tools/server.sh (tools/test_lib.sh) expands ${anchor:<id>} ("x z"), ${anchor:<id>.x}, ${anchor:<id>.z+40}, ${probe:<id>}
("x y z", or "x z" without a y) and ${probe:<id>.y+1} in every line of a tests/ingame/*.rcon before it is sent over RCON,
so a test never hard-codes a coordinate that the data owns. Run `python tools/anchors_env.py` to print the file.
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANCHORS = ROOT / "design" / "data" / "anchors.toml"
PROBES = ROOT / "design" / "data" / "lerfing" / "probes.toml"
ENV = ROOT / "tests" / "anchors.env"
ID = re.compile(r"^[a-z0-9_]+$")
HEADER = (
    "# GENERATED by tools/gen_data.py (tools/anchors_env.py) from design/data/anchors.toml and design/data/lerfing/probes.toml.\n"
    "# Do not edit; edit the TOML and run python tools/gen_data.py. tools/server.sh substitutes ${anchor:<id>[.x|.z][+-N]} and\n"
    "# ${probe:<id>[.<field>][+-N]} from this file in every line of tests/ingame/*.rcon.\n"
)


def _load(path: Path) -> dict:
    if not path.is_file():
        return {}
    return tomllib.loads(path.read_text(encoding="utf-8"))


def anchor_lines(table: dict) -> list[str]:
    out = []
    for aid, row in table.items():
        if aid == "keepout" or not isinstance(row, dict):
            continue  # [keepout.<id>] are boxes, not points
        if not ID.match(aid):
            raise SystemExit(f"anchors.toml: id {aid!r} is not [a-z0-9_]+ (the test tokens need it)")
        for field in ("x", "z"):
            if not isinstance(row.get(field), int) or isinstance(row.get(field), bool):
                raise SystemExit(f"anchors.toml: {aid}.{field} must be an integer (tests/anchors.env)")
            out.append(f"anchor.{aid}.{field}={row[field]}")
    return out


def probe_lines(table: dict) -> list[str]:
    out = []
    for pid, row in table.items():
        if not isinstance(row, dict):
            raise SystemExit(f"probes.toml: top-level key {pid!r} must be a [<id>] table")
        if not ID.match(pid):
            raise SystemExit(f"probes.toml: id {pid!r} is not [a-z0-9_]+")
        for key, value in row.items():
            if key == "what":
                continue  # prose
            if isinstance(value, bool) or not isinstance(value, (int, float, str)):
                raise SystemExit(f"probes.toml: {pid}.{key} must be an integer, a number or a string")
            if isinstance(value, str) and ("\n" in value or "=" in value and key not in ("block", "biome")):
                raise SystemExit(f"probes.toml: {pid}.{key} cannot be written to an env file")
            out.append(f"probe.{pid}.{key}={value}")
        for need in ("kind", "x", "z"):
            if need not in row:
                raise SystemExit(f"probes.toml: {pid} lacks {need}")
    return out


def text() -> str:
    body = anchor_lines(_load(ANCHORS)) + probe_lines(_load(PROBES))
    return HEADER + "\n".join(sorted(body)) + "\n"


def render() -> dict[Path, str]:
    return {ENV: text()}


if __name__ == "__main__":
    sys.stdout.write(text())
