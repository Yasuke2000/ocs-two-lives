#!/usr/bin/env python3
"""Write the two BlueMap map configs with static markers from the canon data.

Usage: gen_map.py           write pack/config/bluemap/maps/tensura.conf and mortal_realm.conf
       gen_map.py --check   exit 1 if they are out of date (stdout names the file)

Sources: pack/config/ttl/canon_regions.json (22 regions, lerfing.inner), pack/config/ttl/canon_map.txt (which chunk
belongs to which region; the `# origin <col> <row>` line says where world 0, 0 is) and design/data/anchors.toml (every
canon place in Lerfing's coordinates, design/architecture/lerfing-import.md). The render mask is Lerfing's imported
inner tiles plus PAD blocks of the generated sea ring. Marker sets written into the Tensura map:
  regions    one label per canon region, on the region cell nearest its centroid (seen when zoomed out)
  landmarks  every anchor except those with map = false (internal NPC, boss and camp spots)
Live markers (nations, wars, events) are not written here: they need BlueMap's MarkerAPI from a script.
Nothing else in pack/config/bluemap is generated (core, webapp, webserver, storages are edited by hand).
"""
import html
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANON = ROOT / "pack" / "config" / "ttl" / "canon_regions.json"
GRID = ROOT / "pack" / "config" / "ttl" / "canon_map.txt"
ANCHORS = ROOT / "design" / "data" / "anchors.toml"
OUT = ROOT / "pack" / "config" / "bluemap" / "maps"

WORLD = "world-ttl"          # level-name of the server (docs/server.md)
PAD = 256                    # blocks of the generated sea ring rendered around Lerfing's inner tiles
MORTAL_RADIUS = 3000         # Mortal Realm is endless; only render this square around Wayfarer's Rest (0, 0)
MARKER_Y = 100               # markers float at this height in the 3D view
REGION_MIN_DISTANCE = 600    # region labels hide when the camera is closer than this
LANDMARK_MAX_DISTANCE = 6000  # landmark pins hide when the camera is further than this

HEADER = """# GENERATED by tools/gen_map.py from pack/config/ttl/canon_regions.json, canon_map.txt and design/data/anchors.toml - do not edit by hand.
# Change the knobs at the top of the script (world name, padding, marker distances), then run
# `python tools/gen_map.py`. Everything else about BlueMap is in core.conf, webapp.conf and webserver.conf.
"""


def q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def load_grid() -> tuple[int, int, list[str]]:
    origin = None
    rows = []
    for line in GRID.read_text(encoding="utf-8").splitlines():
        m = re.match(r"# origin (\d+) (\d+)", line)
        if m:
            origin = (int(m[1]), int(m[2]))
        elif line and not line.startswith("#"):
            rows.append(line)
    if origin is None:
        raise SystemExit("canon_map.txt has no '# origin <col> <row>' line")
    return origin[0], origin[1], rows


def region_labels(canon: dict, oc: int, orow: int, rows: list[str]) -> tuple[list[dict], tuple[int, int, int, int]]:
    cells: dict[str, list[tuple[int, int]]] = {}
    x0 = z0 = 10 ** 9
    x1 = z1 = -10 ** 9
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == ".":
                continue
            x, z = (c - oc) * 16, (r - orow) * 16
            x0, z0, x1, z1 = min(x0, x), min(z0, z), max(x1, x + 16), max(z1, z + 16)
            if ch != "~":
                cells.setdefault(ch, []).append((x + 8, z + 8))
    out = []
    for key, region in canon["regions"].items():
        pts = cells.get(key)
        if not pts:
            continue
        cx = sum(p[0] for p in pts) / len(pts)
        cz = sum(p[1] for p in pts) / len(pts)
        x, z = min(pts, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cz) ** 2)
        out.append({"key": key, "name": region["name"], "colour": region.get("colour", [255, 255, 255]),
                    "x": x, "z": z})
    return out, (x0, z0, x1, z1)


def landmarks() -> list[dict]:
    anchors = tomllib.loads(ANCHORS.read_text(encoding="utf-8"))
    return [{"name": a["name"], "kind": a["kind"], "x": a["x"], "z": a["z"]}
            for k, a in anchors.items() if k != "keepout" and a.get("map", True)]


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40].strip("-")


def tensura_conf(canon: dict) -> str:
    oc, orow, rows = load_grid()
    regions, _ = region_labels(canon, oc, orow, rows)
    x0, z0, x1, z1 = canon["lerfing"]["inner"]
    start = tomllib.loads(ANCHORS.read_text(encoding="utf-8"))["tempest"]
    o = [HEADER, "# Life 2: the canon Tensura continent in the overworld of world-ttl (design/lore/world.md).",
         f"world: {q(WORLD)}", 'dimension: "minecraft:overworld"', 'name: "Tensura (Life 2)"', "sorting: 0",
         f"start-pos: {{ x: {start['x']}, z: {start['z']} }}", "",
         "# Only Lerfing's imported map plus a strip of the generated sea is rendered; the free lands further out are not.",
         "render-mask: [",
         "  {",
         f"    min-x: {x0 - PAD}", f"    max-x: {x1 + PAD}", f"    min-z: {z0 - PAD}", f"    max-z: {z1 + PAD}",
         "  }", "]", "render-edges: true", "edge-light-strength: 8", "",
         'storage: "file"', "enable-perspective-view: true", "enable-flat-view: true",
         "enable-free-flight-view: true", "enable-hires: true", "ignore-missing-light-data: false", "",
         "marker-sets: {", "  regions: {", '    label: "Regions"', "    toggleable: true", "    default-hidden: false",
         "    sorting: 0", "    markers: {"]
    for r in regions:
        rgb = ",".join(str(v) for v in r["colour"])
        label = ('<div style="transform:translate(-50%,-50%);padding:2px 8px;border-radius:4px;color:#fff;'
                 'font:600 13px sans-serif;white-space:nowrap;text-shadow:0 0 3px #000;'
                 f'background:rgba({rgb},.7)">{html.escape(r["name"])}</div>')
        o += [f"      region-{r['key'].lower()}: {{", '        type: "html"',
              f"        position: {{ x: {r['x']}, y: {MARKER_Y}, z: {r['z']} }}", f"        label: {q(r['name'])}",
              f"        html: {q(label)}", "        anchor: { x: 0, y: 0 }",
              f"        min-distance: {REGION_MIN_DISTANCE}", "      }"]
    o += ["    }", "  }", "  landmarks: {", '    label: "Canon landmarks"', "    toggleable: true",
          "    default-hidden: false", "    sorting: 1", "    markers: {"]
    seen: set[str] = set()
    for lm in landmarks():
        mid = slug(lm["name"])
        while mid in seen:
            mid += "-2"
        seen.add(mid)
        detail = f"<b>{html.escape(lm['name'])}</b><br>{lm['kind']} ({lm['x']}, {lm['z']})"
        o += [f"      {mid}: {{", '        type: "poi"',
              f"        position: {{ x: {lm['x']}, y: {MARKER_Y}, z: {lm['z']} }}", f"        label: {q(lm['name'])}",
              f"        detail: {q(detail)}", f"        max-distance: {LANDMARK_MAX_DISTANCE}", "      }"]
    o += ["    }", "  }", "}", ""]
    return "\n".join(o)


def mortal_conf() -> str:
    r = MORTAL_RADIUS
    o = [HEADER, "# Life 1: the Mortal Realm (ttl:mortal_realm), where every soul starts at Wayfarer's Rest.",
         "# The Spirit Corridor (ttl:spirit_corridor) and the Mortal Nether/End are deliberately not mapped.",
         f"world: {q(WORLD)}", 'dimension: "ttl:mortal_realm"', 'name: "Mortal Realm (Life 1)"', "sorting: 1",
         "start-pos: { x: 0, z: 0 }", "", "render-mask: [", "  {", f"    min-x: {-r}", f"    max-x: {r}",
         f"    min-z: {-r}", f"    max-z: {r}", "  }", "]", "render-edges: true", "edge-light-strength: 8", "",
         'storage: "file"', "enable-perspective-view: true", "enable-flat-view: true",
         "enable-free-flight-view: true", "enable-hires: true", "ignore-missing-light-data: false", "",
         "marker-sets: {", "  spawn: {", '    label: "Spawn"', "    toggleable: true", "    default-hidden: false",
         "    sorting: 0", "    markers: {", "      wayfarers-rest: {", '        type: "poi"',
         f"        position: {{ x: 0, y: {MARKER_Y}, z: 0 }}", '        label: "Wayfarer\'s Rest"',
         '        detail: "<b>Wayfarer\'s Rest</b><br>Where every first life begins"', "      }", "    }", "  }", "}", ""]
    return "\n".join(o)


def render() -> dict[Path, str]:
    canon = json.loads(CANON.read_text(encoding="utf-8"))
    return {OUT / "tensura.conf": tensura_conf(canon), OUT / "mortal_realm.conf": mortal_conf()}


def main() -> None:
    files = render()
    if "--check" in sys.argv:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"{p.relative_to(ROOT).as_posix()} is out of date: run python tools/gen_map.py")
        sys.exit(1 if stale else 0)
    OUT.mkdir(parents=True, exist_ok=True)
    for p, t in files.items():
        p.write_text(t, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
