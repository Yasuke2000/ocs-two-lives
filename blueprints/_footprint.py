"""Ground data for placing a flat settlement build (a village on a ground layer) on real terrain.

Same data format as _dwargon_footprint.py (read by a KubeJS placer such as life/tempest.js), but for builds
whose whole box is solid ground up to a ground layer with air above, instead of a carved mountain.

The grid covers the structure box plus MARGIN columns on every side, row-major (z outer, x inner), cell
(0, 0) = blueprint column (-MARGIN, -MARGIN). Per cell, two run-length encoded values ([value, count, ...];
NONE = nothing to do), heights relative to the structure's base layer:

- fill:  fill the gap between the real ground and this layer (exclusive). Box columns: the lowest non-air
         block of the build, so nothing floats. Margin columns: a 1:1 earth skirt falling away from the
         ground layer, so a village set above low ground meets it in a slope.
- clear: remove terrain from this layer upward. Box columns whose highest block is air: from just above the
         box (the box itself already holds the air). Margin columns: a 1:1 cut slope rising from the ground
         layer, so hills next to the village are cut back instead of walling it in. The placer only clears a
         margin column when its terrain (not its trees) reaches above the cut, so the forest round it stays.
"""
import json
import math

AIR = "minecraft:air"
MARGIN = 8
NONE = -999


def _rle(values):
    out = []
    for v in values:
        if out and out[-2] == v:
            out[-1] += 1
        else:
            out += [v, 1]
    return out


def settlement_footprint(bp, var: str, source: str, ground: int, probes, arrival, parts, margin: int = MARGIN) -> str:
    sx, sy, sz = bp.size
    low, high, top_state = {}, {}, {}
    for (x, y, z), state in bp.blocks.items():
        k = (x, z)
        if state != AIR and y < low.get(k, sy):
            low[k] = y
        if y > high.get(k, -1):
            high[k] = y
            top_state[k] = state
    w, l = sx + 2 * margin, sz + 2 * margin
    fills, clears = [], []
    for gz in range(l):
        for gx in range(w):
            x, z = gx - margin, gz - margin
            if 0 <= x < sx and 0 <= z < sz:
                fills.append(low.get((x, z), NONE))
                clears.append(high[(x, z)] + 1 if top_state.get((x, z)) == AIR else NONE)
                continue
            d = math.ceil(math.hypot(max(0, -x, x - sx + 1), max(0, -z, z - sz + 1)))
            fills.append(ground + 1 - d)
            clears.append(ground + 1 + d)
    data = {
        "size": list(bp.size), "margin": margin, "grid": [w, l], "none": NONE, "ground": ground,
        "arrival": list(arrival), "probes": [list(p) for p in probes],
        "parts": list(parts) if parts else [0],
        "fill": _rle(fills), "clear": _rle(clears),
    }
    body = json.dumps(data, separators=(",", ":"))
    return ("// priority: 200\n"
            f"// GENERATED by tools/build_structures.py from {source} (blueprints/_footprint.py). Do not edit.\n"
            f"const {var} = {body}\n")
