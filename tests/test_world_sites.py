"""Own world, WP-W5: every anchor's site and every build on it (python -I -m unittest discover -s tests)

design/architecture/own-world.md §3.3, §4: world/sites.toml is generated by tools/world/sites_from_builds.py from the
build footprints (generated/builds.js, the Tempest and Dwargon footprints, landmarks.toml reach, arrival.toml
safe_radius) and, once they exist, world/map.svg and the rasters. These tests keep it current and check that every
build fits its site, that builds switch to ground = "fixed" with a walking level, and that every carve site keeps at
least 6 blocks of rock over its roof: in the file (min_cover) and on rasters (each carve build cut into a synthetic
mountain by tools/world/svg2rasters.py, sampled the way the generator samples). Replaces test_lerfing_anchors.py at
the switch (WP-W13); until then both run.
"""
import math
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "world"))
import sites_from_builds as sfb  # noqa: E402
import svg2rasters as s2r  # noqa: E402

CARVE_MAP = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8000 -6000 16000 12000">
  <g id="coast"><polygon points="-1000,-800 1000,-800 1000,600 -1000,600"/></g>
  <g id="lakes"/><g id="rivers"/><g id="hills"/><g id="forests"/><g id="biomes"/><g id="roads"/><g id="labels"/>
  <g id="mountains"><polygon data-peak="260" points="-880,-760 880,-760 880,150 -880,150"/>
    <polyline class="ridge" points="-800,-520 800,-520"/></g>
  <g id="regions"><polygon data-letter="D" points="-1100,-900 1100,-900 1100,700 -1100,700"/></g>
  <g id="sites">%s</g>
</svg>
"""
CARVE_SPOTS = ((-620, -250), (0, -250), (620, -250))


class WorldSites(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.src = sfb.Sources()
        cls.existing = sfb.load_existing(sfb.SITES_TOML)
        svg = sfb.svg_sites(sfb.SVG) if sfb.SVG.is_file() else None
        cls.sites, cls.reqs = sfb.derive(cls.src, svg, sfb.raster_grounds(sfb.RASTERS), cls.existing)

    def test_sites_toml_is_current(self):
        self.assertTrue(sfb.SITES_TOML.is_file(), "world/sites.toml is missing")
        self.assertEqual(sfb.SITES_TOML.read_text(encoding="utf-8"), sfb.dumps(self.sites, self.existing),
                         "world/sites.toml is stale: run python -I tools/world/sites_from_builds.py")

    def test_one_site_per_anchor(self):
        tables = {k for k, v in self.existing.items() if k not in sfb.EXTRA_TABLES and isinstance(v, dict)}
        self.assertEqual(tables, set(self.src.anchors))
        self.assertLessEqual(set(sfb.FIRST_PASS), set(self.src.anchors))
        for aid, rec in self.sites.items():
            self.assertIn(rec["site"], sfb.SITE_KINDS, aid)

    def test_no_misfits(self):
        self.assertEqual(sfb.problems(self.sites, self.reqs), [])

    def test_every_build_fits_its_site(self):
        builds = [a for a in self.src.anchors.values() if a.get("kind") in ("build", "settlement")]
        self.assertGreaterEqual(len(builds), 30)
        for a in builds:
            rec, req = self.sites[a["id"]], self.reqs[a["id"]]
            sx, sz = req["box"]
            px, pz = req["plate"]
            with self.subTest(a["id"]):
                self.assertEqual(rec["box"], [sx, sz])
                self.assertGreaterEqual(rec["r"], rec["min_r"])
                # design §3.3: r = half the box diagonal + 12, and the whole plate (box + margin) inside r
                self.assertGreaterEqual(rec["r"], math.hypot(sx, sz) / 2 + 12)
                self.assertGreaterEqual(rec["r"], math.hypot(px, pz) / 2)
                self.assertGreaterEqual(min(px - sx, pz - sz), 2 * 8)
                if "y" in rec:
                    self.assertLess(rec["y"] + rec["height"], sfb.BUILD_LIMIT)
            if a.get("kind") == "build":
                self.assertEqual(rec["ground"], "fixed", a["id"])
                fp = self.src.footprints[a["build"]]
                self.assertEqual(rec["box"], [fp["size"][0], fp["size"][2]], a["id"])

    def test_landmarks_and_arrival(self):
        for a in self.src.anchors.values():
            rec = self.sites[a["id"]]
            if a.get("kind") == "landmark":
                reach = self.src.landmarks[a["landmark"]]["reach"]
                self.assertGreaterEqual(rec["r"], reach + 8, a["id"])
            elif a.get("kind") == "arrival":
                self.assertGreaterEqual(rec["r"], self.src.safe_radius + 12)
            elif a.get("kind") in ("pin", "spot"):
                self.assertEqual(rec["r"], sfb.PIN_R, a["id"])
                self.assertNotIn("plate", rec, a["id"])

    def test_first_pass_grounds(self):
        self.assertEqual(self.sites["tempest"]["y"], 70)
        self.assertEqual(self.sites["dwargon"]["y"], 146)       # BASE 142 + the gate's walking level 4
        self.assertEqual(self.sites["dragons_nest"]["y"], 272)
        self.assertGreaterEqual(self.sites["tempest"]["r"], math.hypot(192, 192) / 2 + 12)   # the growth square

    def test_carve_sites_keep_cover_in_the_file(self):
        carves = [aid for aid, rec in self.sites.items() if rec["site"] == "carve"]
        self.assertTrue({"dwargon", "sealed_cave"} <= set(carves), carves)
        for aid in carves:
            self.assertGreaterEqual(self.sites[aid]["min_cover"], 6, aid)
            if self.reqs[aid].get("build"):
                self.assertIs(self.sites[aid].get("clear_above"), False, aid)

    def test_carve_sites_keep_cover_on_rasters(self):
        """Each carve site with a roof, cut into a synthetic mountain: >= min_cover over every roof column."""
        roofed = [aid for aid, rec in self.sites.items() if rec["site"] == "carve" and self.reqs[aid].get("roof_cols")]
        self.assertTrue(roofed)
        for n in range(0, len(roofed), len(CARVE_SPOTS)):
            group = roofed[n:n + len(CARVE_SPOTS)]
            circles = "".join('<circle data-id="%s" data-site="carve" cx="%d" cy="%d" r="%d"/>'
                              % (aid, x, z, self.sites[aid]["r"]) for aid, (x, z) in zip(group, CARVE_SPOTS))
            world = s2r.build(CARVE_MAP % circles, s2r.Options(sea_margin=128, region=256), sfb.SITES_TOML)
            with tempfile.TemporaryDirectory() as tmp:
                s2r.write_outputs(world, tmp)
            by_id = {t.id: t for t in world.site_list}
            for aid in group:
                t, req = by_id[aid], world.reqs[aid]
                ax, _, az = req["anchor"]
                bx0, bz0 = t.x - ax, t.z - az
                worst = min(world.sample(bx0 + bx + 0.5, bz0 + bz + 0.5) - (t.ground + rel)
                            for (bx, bz), rel in req["roof_cols"].items())
                with self.subTest(aid):
                    self.assertGreaterEqual(t.cover, 6)
                    self.assertGreaterEqual(worst, t.cover, "%s: %.1f blocks of cover" % (aid, worst))
                    if "plate_y" in self.sites[aid]:
                        self.assertEqual(t.ground, self.sites[aid]["plate_y"])


if __name__ == "__main__":
    unittest.main()
